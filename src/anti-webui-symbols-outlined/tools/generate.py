#!/usr/bin/env python3
"""Generates `fonts/` and `src/generated.rs` from Material Symbols, one small font per icon.

    python3 tools/generate.py <the font> <its .codepoints file>

Needs fontTools. See `docs/design/18-icons.md`.
"""

import multiprocessing
import pathlib
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

CRATE = pathlib.Path(__file__).resolve().parent.parent
DROPPED_TABLES = ("GSUB", "STAT", "gasp", "prep", "DSIG", "meta")


def split(args):
    source, codepoint = args
    # The box of the whole font stays: it says how far any glyph may reach.
    font = TTFont(source, lazy=True, recalcBBoxes=False)
    options = subset.Options()
    options.layout_features = []
    options.notdef_outline = False
    options.hinting = False
    options.glyph_names = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes={int(codepoint, 16)})
    subsetter.subset(font)
    for table in DROPPED_TABLES:
        if table in font:
            del font[table]
    # A font without a family isn't taken as a font, even when it gets registered under a name.
    names = font["name"]
    names.names = [n for n in names.names if n.nameID == 1 and n.platformID == 3]
    font.save(CRATE / "fonts" / f"{codepoint}.ttf")


def constant(name):
    name = re.sub(r"[^A-Z0-9_]", "_", name.upper())
    return f"_{name}" if name[0].isdigit() else name


def main():
    source, codepoints = sys.argv[1:3]
    by_codepoint = {}
    for line in open(codepoints):
        name, codepoint = line.split()
        by_codepoint.setdefault(codepoint, []).append(constant(name))
    (CRATE / "fonts").mkdir(exist_ok=True)
    for old in (CRATE / "fonts").glob("*.ttf"):
        old.unlink()
    with multiprocessing.Pool() as pool:
        pool.map(split, [(source, c) for c in sorted(by_codepoint)], chunksize=16)

    out = ["// Generated by tools/generate.py.", "use crate::Symbol;", ""]
    for codepoint, names in sorted(by_codepoint.items()):
        first, *others = sorted(names)
        out.append(
            f"static S_{codepoint.upper()}: Symbol = Symbol {{ "
            f'font: include_bytes!("../fonts/{codepoint}.ttf"), '
            f'family: "material-symbols-outlined-{codepoint}", '
            f"ch: '\\u{{{codepoint}}}' }};"
        )
        out.append(f"pub const {first}: &Symbol = &S_{codepoint.upper()};")
        out.extend(f"pub use self::{first} as {other};" for other in others)
    (CRATE / "src" / "generated.rs").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
